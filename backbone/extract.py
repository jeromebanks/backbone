"""Per-document structured extraction with a content-addressed cache.

Cache key: (sha256 of document bytes, EXTRACTOR_VERSION, model). Cached results live in
cache/extractions/<sha256>.<version>.<model>.json so the abstraction can be rebuilt from scratch
with zero LLM calls, and re-ingesting unchanged documents is free.
"""
from __future__ import annotations

import json
from pathlib import Path

from . import EXTRACTOR_VERSION
from .db import ROOT
from .llm import DEFAULT_MODEL, LLMResult, complete_json
from .schema import Extraction

CACHE_DIR = ROOT / "cache" / "extractions"

SYSTEM = """You are a meticulous clinical-records abstractor. You read ONE source document from a behavioral-health \
chart and record, in the required JSON structure, exactly what THIS document asserts. Downstream software reconciles \
documents against each other and does all arithmetic; your job is faithful, literal extraction with verbatim evidence.

General rules
- Record only what the document states. Do not infer facts from other documents, do not resolve conflicts, \
do not decide which record is authoritative, and do not compute durations. Copy a number of minutes into \
stated_minutes only if the document itself states it.
- Times: 24-hour "HH:MM" local. Dates: "YYYY-MM-DD" (the documents are from the year printed in them).
- Every quote must be copied verbatim from the document (a short excerpt, one sentence or one table row). \
Never paraphrase inside a quote field. Do not join non-adjacent text in one quote; use several quotes instead.
- Identifiers (encounter, appointment, form, authorization IDs) must be copied exactly.

document
- document_id: the "Document ID" printed in the header, if any.
- signed: true only if a clinician or staff signature/attestation is present in the document. finality: \
"draft" for drafts/unsigned templates, "final" when stated final or signed, else "unknown".
- relations: record links this document states to OTHER records, using keys the text gives (encounter_id, field, \
old/new values, form_id, original date):
  * corrects_field - the document explicitly corrects a field of an earlier record (give field, old_value, new_value).
  * retransmits_original - the document is a resent/re-received/indexed copy of an earlier record.
  * copies_measurement - the document copies or imports a measurement completed earlier (give form_id, original_date).
  * companion_record - a second clinician's record of the same encounter.
  * references - any other mention of another record (e.g. "recorded in X's primary note").

service_events - one entry per service/appointment the document gives information about
- A document may contain several events (e.g. a schedule table lists many appointments; a register lists several \
dates). A document may also contain several record types for the same encounter (e.g. a clinical note plus an \
attached platform connection export, or a draft note plus a billing charge): emit one event per record type, \
each with its own evidence_type.
- encounter_id: the encounter THIS event describes. If the document is a phone call, message, or notice ABOUT an \
appointment, emit (a) an event for the appointment itself if the document states its status (with its encounter_id), \
and (b) a separate event for the call/notice with encounter_id null and related_encounter_id set.
- service_type: individual_therapy, group_therapy, family_therapy (patient present with family), family_collateral \
(family/partner WITHOUT the patient), medication_management, care_coordination (professionals only), outreach_call, \
administrative, other. Classify by what the service is, as the document describes it.
- evidence_type: what kind of record the assertion comes from: clinical_note, attendance_record (roster, register, \
attestation), attendance_correction, schedule_listing (appointment desk export/status list), platform_log (telehealth \
connection export), billing, draft_template (autogenerated/template/unsigned draft text), retransmitted_copy \
(resent/copied/imported copy of an earlier record), administrative_notice, other.
- disposition: as the record states it (attended_full, attended_partial, attended, no_show, patient_cancelled, \
clinic_cancelled, scheduled_only, unknown).
- patient_present: whether THIS patient was present for any of the service (yes, no, partial, unknown).
- scheduled: the booked/scheduled interval if stated. patient_arrival / patient_departure: when the patient \
arrived/joined and left, if stated.
- patient_contact_intervals: intervals of actual patient contact the document explicitly states (e.g. "Patient \
contact 15:00-15:30", or two call segments 08:00-08:10 and 08:15-08:40, or "patient present with family \
16:20-16:50"). Leave empty \
when the document gives only a scheduled interval or only arrival/departure times.
- nontherapeutic_intervals: intervals inside the session with no therapy for this patient: group breaks (kind \
"break"), lost connections ("disconnection"), portions where the session ran without this patient ("patient_absent").
- quotes: 1-4 verbatim excerpts supporting the date, times, disposition and presence.

assessments - standardized instruments (e.g. PHQ-9) whose result appears in the document. completed_date is when the \
patient completed it, not when it was received or imported. Set is_copy_of_earlier=true if the document only \
copies/imports/restates a result completed earlier (e.g. an import receipt, or a note restating a prior score as \
background). A score mentioned only as a comparison to an earlier one ("higher than last month's score of 7") is NOT \
an assessment entry.

observations - clinically meaningful statements about symptoms, functioning, safety, engagement or progress \
(4-10 per clinical document, fewer for administrative ones; none if the document has no clinical content). Use \
source = patient_report, clinician_observation, clinician_assessment (clinician's formulation or progress judgement), \
collateral_report (family/others), or measurement. domain "overall_progress" for statements about improvement/progress.

plan_requirements - measurable participation/frequency goals in treatment plans (e.g. minimum therapy days or minutes \
per week). Record each metric separately, the service types that count and that are excluded, whether the patient must \
be present, and the effective dates the plan states. Leave the list empty for documents that are not plans."""

USER_TEMPLATE = """Source file name: {filename}

<document>
{text}
</document>

Extract this document into the required JSON structure."""


def cache_path(sha256: str, model: str) -> Path:
    return CACHE_DIR / f"{sha256}.{EXTRACTOR_VERSION}.{model}.json"


def load_cached(sha256: str, model: str = DEFAULT_MODEL) -> dict | None:
    p = cache_path(sha256, model)
    if p.exists():
        return json.loads(p.read_text())
    return None


def extract_document(sha256: str, filename: str, text: str, *, model: str = DEFAULT_MODEL,
                     effort: str = "high") -> tuple[Extraction, dict]:
    """Return (extraction, meta). meta records latency/tokens/cost and whether it came from cache."""
    cached = load_cached(sha256, model)
    if cached is not None:
        meta = dict(cached["meta"], from_cache=True)
        return Extraction.model_validate(cached["extraction"]), meta
    res: LLMResult = complete_json(SYSTEM, USER_TEMPLATE.format(filename=filename, text=text), Extraction,
                                   model=model, effort=effort)
    meta = {
        "model": res.model, "extractor_version": EXTRACTOR_VERSION, "effort": effort,
        "latency_ms": res.latency_ms, "input_tokens": res.input_tokens, "output_tokens": res.output_tokens,
        "cost_usd": res.cost_usd, "attempts": res.attempts, "from_cache": False,
    }
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    cache_path(sha256, model).write_text(json.dumps(
        {"sha256": sha256, "filename": filename, "meta": meta, "extraction": res.data.model_dump()}, indent=2))
    return res.data, meta
