"""Extraction contract: what the LLM may assert about ONE document.

Design rules (enforced by the prompt and by code downstream):
- The model records what the document states; it never computes durations or reconciles across documents.
- Times are 24h "HH:MM" local, dates "YYYY-MM-DD".
- Every assertion carries verbatim quotes; code verifies them against the document text (evidence.py).
- Cross-document links are expressed through keys the text states (encounter IDs, form IDs, dates),
  never through other documents' IDs, which a single-document call cannot know.
"""
from __future__ import annotations

from typing import Literal, Optional

from pydantic import BaseModel, ConfigDict, Field

ServiceType = Literal[
    "individual_therapy",
    "group_therapy",
    "family_therapy",
    "family_collateral",       # family/partner contact WITHOUT the patient
    "medication_management",
    "care_coordination",
    "outreach_call",           # scheduling / reminder / missed-visit calls
    "administrative",
    "other",
]

EvidenceType = Literal[
    "clinical_note",           # signed (or unsigned) clinician narrative of the service itself
    "attendance_record",       # roster / attendance register / attestation row
    "attendance_correction",   # explicit correction of an attendance field
    "schedule_listing",        # appointment desk export / schedule status listing
    "platform_log",            # telehealth connection export, system logs
    "billing",                 # charge / claim rows
    "draft_template",          # autogenerated or template text, drafts
    "retransmitted_copy",      # a resent / copied / imported copy of an earlier record
    "administrative_notice",   # cancellation notices, letters
    "other",
]

Disposition = Literal[
    "attended_full",
    "attended_partial",
    "attended",                # attended, extent not stated
    "no_show",
    "patient_cancelled",
    "clinic_cancelled",
    "scheduled_only",          # listed as scheduled, outcome not stated
    "unknown",
]


class Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class Interval(Strict):
    start: str = Field(description="HH:MM 24h local")
    end: str = Field(description="HH:MM 24h local")


class NonTherapeuticInterval(Strict):
    start: str
    end: str
    kind: Literal["break", "disconnection", "patient_absent", "other"] = Field(
        description="break = no therapy for anyone; disconnection = lost connection; "
        "patient_absent = session running but THIS patient not present (e.g. partner-only portion)"
    )
    quote: str


class Relation(Strict):
    type: Literal[
        "corrects_field",        # this document explicitly corrects a field of an earlier record
        "retransmits_original",  # this document is a resent/re-received copy of an earlier record
        "copies_measurement",    # this document copies/imports a measurement completed earlier
        "companion_record",      # a second clinician's record of the same encounter
        "references",            # any other reference to another record/encounter
    ]
    encounter_id: Optional[str]
    field: Optional[Literal["arrival", "departure", "disposition", "contact_interval", "service_type", "other"]]
    old_value: Optional[str]
    new_value: Optional[str]
    form_id: Optional[str]
    original_date: Optional[str] = Field(description="Original service/completion/signature date of the referenced record, YYYY-MM-DD")
    quote: str


class DocumentInfo(Strict):
    document_id: Optional[str] = Field(description="Document ID exactly as printed in the header, if any")
    title: str = Field(description="Short description of what the document is")
    signed: bool = Field(description="True only if the document carries a clinician/staff signature or attestation")
    signed_at: Optional[str] = Field(description="YYYY-MM-DDTHH:MM of the (first) signature, if stated")
    received_at: Optional[str] = Field(description="YYYY-MM-DDTHH:MM when received/imported/filed, if stated")
    finality: Literal["final", "draft", "unknown"]
    patient_name: Optional[str]
    patient_mrn: Optional[str]
    patient_dob: Optional[str]
    relations: list[Relation]


class ServiceEvent(Strict):
    encounter_id: Optional[str] = Field(description="ID of the encounter THIS event describes. Null for a separate call/message that merely refers to an appointment.")
    related_encounter_id: Optional[str] = Field(description="Encounter an outreach call/notice is about, when this event is not that encounter itself")
    appointment_id: Optional[str]
    service_date: str = Field(description="YYYY-MM-DD")
    service_type: ServiceType
    modality: Literal["in_person", "video", "phone", "portal", "unknown"]
    evidence_type: EvidenceType = Field(description="What kind of record this assertion comes from (a document can contain several)")
    disposition: Disposition
    patient_present: Literal["yes", "no", "partial", "unknown"] = Field(description="Was THIS patient present for (part of) the service?")
    scheduled: Optional[Interval] = Field(description="Booked/scheduled interval, if stated")
    patient_arrival: Optional[str] = Field(description="HH:MM the patient arrived/joined, if stated")
    patient_departure: Optional[str] = Field(description="HH:MM the patient left, if stated")
    patient_contact_intervals: list[Interval] = Field(description="Intervals of actual patient contact explicitly stated (e.g. '09:00–09:50', or two call segments). Empty if not stated.")
    nontherapeutic_intervals: list[NonTherapeuticInterval]
    stated_minutes: Optional[int] = Field(description="Duration in minutes ONLY if the document states a number; never compute it")
    clinicians: list[str]
    quotes: list[str] = Field(description="1-4 verbatim excerpts supporting date, times, disposition and presence")


class Assessment(Strict):
    instrument: str = Field(description="e.g. PHQ-9, GAD-7")
    total_score: Optional[float]
    item_scores: list[str] = Field(description="Item scores as stated, e.g. 'Item 9: 0'")
    completed_date: Optional[str] = Field(description="YYYY-MM-DD the patient completed it (not the import/receipt date)")
    completed_time: Optional[str]
    form_id: Optional[str]
    is_copy_of_earlier: bool = Field(description="True if this document only copies/imports a result completed earlier")
    quote: str


class Observation(Strict):
    date: str = Field(description="YYYY-MM-DD the observation refers to")
    domain: Literal["mood", "sleep", "anxiety", "avoidance", "functioning", "safety", "engagement", "overall_progress", "other"]
    source: Literal["patient_report", "clinician_observation", "clinician_assessment", "collateral_report", "measurement"]
    statement: str = Field(description="One-sentence neutral paraphrase")
    quote: str


class PlanRequirement(Strict):
    metric: Literal["therapy_days", "patient_present_minutes", "sessions", "other"]
    threshold: float
    comparator: Literal[">=", ">", "<=", "<", "=="]
    period: Literal["week_mon_sun", "week_other", "month", "episode", "other"]
    counted_service_types: list[ServiceType]
    excluded_service_types: list[ServiceType]
    requires_patient_present: bool
    effective_start: Optional[str] = Field(description="YYYY-MM-DD the requirement takes effect")
    effective_end: Optional[str] = Field(description="YYYY-MM-DD the requirement ends, if stated")
    quote: str


class Extraction(Strict):
    document: DocumentInfo
    service_events: list[ServiceEvent]
    assessments: list[Assessment]
    observations: list[Observation]
    plan_requirements: list[PlanRequirement]


def extraction_json_schema() -> dict:
    return Extraction.model_json_schema()
